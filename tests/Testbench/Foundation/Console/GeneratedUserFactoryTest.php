<?php

declare(strict_types=1);

namespace Hypervel\Tests\Testbench\Foundation\Console;

use Hypervel\Contracts\Foundation\Application as ApplicationContract;
use Hypervel\Filesystem\Filesystem;
use Hypervel\Support\Facades\Hash;
use Hypervel\Testbench\Foundation\Console\InstallCommand;
use Hypervel\Testbench\TestCase;
use Hypervel\Testing\ParallelTesting;
use PHPUnit\Framework\Attributes\Test;

use function Hypervel\Testbench\join_paths;

class GeneratedUserFactoryTest extends TestCase
{
    private int $bcryptRounds = 10;

    #[Test]
    public function itHashesTheGeneratedFactoryPasswordForTheCurrentApplication(): void
    {
        $factory = $this->generatedUserFactory();

        $users = $factory::new()->count(2)->make();

        $this->assertSame($users[0]->password, $users[1]->password);
        $this->assertSame($users[0]->password, $factory::new()->make()->password);
        $this->assertSame(10, password_get_info($users[0]->password)['options']['cost']);

        $this->bcryptRounds = 4;
        $this->reloadApplication();

        $user = $factory::new()->make();

        $this->assertSame(4, password_get_info($user->password)['options']['cost']);
        $this->assertTrue(Hash::check('password', $user->password));
    }

    /**
     * Define environment setup.
     */
    protected function defineEnvironment(ApplicationContract $app): void
    {
        $app->make('config')->set('hashing.bcrypt.rounds', $this->bcryptRounds);
    }

    /**
     * Load the User model and factory generated by package:install.
     *
     * @return class-string
     */
    private function generatedUserFactory(): string
    {
        $namespace = __NAMESPACE__ . '\GeneratedUserFactoryTest';
        $filesystem = new Filesystem;
        $path = ParallelTesting::tempDir('GeneratedUserFactoryTest');
        $replacements = (new class extends InstallCommand {
            /**
             * Get the Workbench stub replacements.
             *
             * @param array{app: string, factories: string, seeders: string} $namespaces
             * @return array<string, string>
             */
            public function replacements(array $namespaces): array
            {
                return $this->workbenchReplacements($namespaces);
            }
        })->replacements([
            'app' => $namespace . '\App\\',
            'factories' => $namespace . '\Database\Factories\\',
            'seeders' => $namespace . '\Database\Seeders\\',
        ]);

        $filesystem->deleteDirectory($path);
        $filesystem->ensureDirectoryExists($path);

        try {
            foreach (['user.stub', 'user-factory.stub'] as $stub) {
                $file = join_paths($path, str_replace('.stub', '.php', $stub));

                $filesystem->put($file, str_replace(
                    array_keys($replacements),
                    array_values($replacements),
                    $filesystem->get(join_paths(dirname(__DIR__, 4), 'src', 'testbench', 'src', 'Foundation', 'Console', 'stubs', $stub))
                ));

                require_once $file;
            }
        } finally {
            $filesystem->deleteDirectory($path);
        }

        return $replacements['{{ WorkbenchUserFactory }}'];
    }
}
