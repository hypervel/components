class AttributesTest extends TestCase
{
    public function testResolvesNameFromAttributeOnATool(): void
    {
        $tool = new AttributeNameTool;

        $this->assertSame('custom-tool-name', $tool->name());
    }

    public function testResolvesTitleFromAttributeOnATool(): void
    {
        $tool = new AttributeTitleTool;

        $this->assertSame('My Custom Title', $tool->title());
    }

    public function testResolvesDescriptionFromAttributeOnATool(): void
    {
        $tool = new AttributeDescriptionTool;

        $this->assertSame('A tool configured via attribute', $tool->description());
    }

    public function testPrefersAttributeOverPropertyForName(): void
    {
        $tool = new AttributeOverridesPropertyNameTool;

        $this->assertSame('attribute-name', $tool->name());
    }

    public function testPrefersAttributeOverPropertyForTitle(): void
    {
        $tool = new AttributeOverridesPropertyTitleTool;

        $this->assertSame('Attribute Title', $tool->title());
    }

    public function testPrefersAttributeOverPropertyForDescription(): void
    {
        $tool = new AttributeOverridesPropertyDescriptionTool;

        $this->assertSame('Attribute description', $tool->description());
    }

    public function testFallsBackToPropertyWhenNoAttributeForName(): void
    {
        $tool = new PropertyOnlyNameTool;

        $this->assertSame('property-name', $tool->name());
    }

    public function testFallsBackToAutoGeneratedWhenNoAttributeOrPropertyForName(): void
    {
        $tool = new FallbackNameTool;

        $this->assertSame('fallback-name-tool', $tool->name());
    }

    public function testResolvesNameFromAttributeOnAResource(): void
    {
        $resource = new AttributeNameResource;

        $this->assertSame('my-resource', $resource->name());
    }

    public function testResolvesUriFromAttributeOnAResource(): void
    {
        $resource = new AttributeUriResource;

        $this->assertSame('file://custom/path', $resource->uri());
    }

    public function testResolvesMimeTypeFromAttributeOnAResource(): void
    {
        $resource = new AttributeMimeTypeResource;

        $this->assertSame('application/json', $resource->mimeType());
    }

    public function testPrefersAttributeOverPropertyForUri(): void
    {
        $resource = new AttributeOverridesPropertyUriResource;

        $this->assertSame('file://attribute/uri', $resource->uri());
    }

    public function testPrefersAttributeOverPropertyForMimeType(): void
    {
        $resource = new AttributeOverridesPropertyMimeTypeResource;

        $this->assertSame('application/xml', $resource->mimeType());
    }

    public function testFallsBackToPropertyWhenNoAttributeForUri(): void
    {
        $resource = new PropertyOnlyUriResource;

        $this->assertSame('file://property/uri', $resource->uri());
    }

    public function testFallsBackToAutoGeneratedWhenNoAttributeOrPropertyForUri(): void
    {
        $resource = new FallbackUriResource;

        $this->assertSame('file://resources/fallback-uri-resource', $resource->uri());
    }

    public function testFallsBackToTextPlainWhenNoAttributeOrPropertyForMimeType(): void
    {
        $resource = new FallbackMimeTypeResource;

        $this->assertSame('text/plain', $resource->mimeType());
    }

    public function testResolvesNameFromAttributeOnAPrompt(): void
    {
        $prompt = new AttributeNamePrompt;

        $this->assertSame('my-prompt', $prompt->name());
    }

    public function testResolvesDescriptionFromAttributeOnAPrompt(): void
    {
        $prompt = new AttributeDescriptionPrompt;

        $this->assertSame('A prompt via attribute', $prompt->description());
    }

    public function testResolvesServerNameFromAttribute(): void
    {
        $transport = new ArrayTransport;
        $server = new AttributeNameServer($transport);

        $context = $server->createContext();

        $this->assertSame('Attribute Server', $context->implementation->name);
    }

    public function testResolvesServerVersionFromAttribute(): void
    {
        $transport = new ArrayTransport;
        $server = new AttributeVersionServer($transport);

        $context = $server->createContext();

        $this->assertSame('2.0.0', $context->implementation->version);
    }

    public function testResolvesServerInstructionsFromAttribute(): void
    {
        $transport = new ArrayTransport;
        $server = new AttributeInstructionsServer($transport);

        $context = $server->createContext();

        $this->assertSame('Custom instructions via attribute', $context->instructions);
    }

    public function testPrefersAttributeOverPropertyForServerName(): void
    {
        $transport = new ArrayTransport;
        $server = new AttributeOverridesPropertyNameServer($transport);

        $context = $server->createContext();

        $this->assertSame('Attribute Server Name', $context->implementation->name);
    }

    public function testFallsBackToPropertyWhenNoAttributeForServerName(): void
    {
        $transport = new ArrayTransport;
        $server = new PropertyOnlyNameServer($transport);

        $context = $server->createContext();

        $this->assertSame('Property Server', $context->implementation->name);
    }

    public function testIncludesAttributesInToArrayOutputForTools(): void
    {
        $tool = new AttributeDescriptionTool;
        $array = $tool->toArray();

        $this->assertSame('A tool configured via attribute', $array['description']);
    }

    public function testIncludesAttributesInToArrayOutputForResources(): void
    {
        $resource = new AttributeUriResource;
        $array = $resource->toArray();

        $this->assertSame('file://custom/path', $array['uri']);
    }

    public function testIncludesAttributesInToArrayOutputForPrompts(): void
    {
        $prompt = new AttributeDescriptionPrompt;
        $array = $prompt->toArray();

        $this->assertSame('A prompt via attribute', $array['description']);
    }

    public function testIgnoresUriAttributeWhenResourceImplementsHasUriTemplate(): void
    {
        $resource = new UriAttributeIgnoredForTemplateResource;

        $this->assertSame('file://users/{userId}', $resource->uri());
    }

    public function testResolvesMultipleAttributesOnASingleClass(): void
    {
        $tool = new MultipleAttributesTool;

        $this->assertSame('multi-tool', $tool->name());
        $this->assertSame('Multi Tool', $tool->title());
        $this->assertSame('A tool with all attributes', $tool->description());
    }

    public function testInheritsAttributeFromParentClass(): void
    {
        $tool = new ChildToolWithoutAttribute;

        $this->assertSame('parent-tool-name', $tool->name());
    }

    public function testChildAttributeOverridesParentAttribute(): void
    {
        $tool = new ChildToolWithOverride;

        $this->assertSame('child-tool-name', $tool->name());
    }

    public function testInheritsAttributeFromParentServerClass(): void
    {
        $transport = new ArrayTransport;
        $server = new ChildServerWithoutAttribute($transport);

        $context = $server->createContext();

        $this->assertSame('Parent Server', $context->implementation->name);
    }

    public function testChildServerAttributeOverridesParentServerAttribute(): void
    {
        $transport = new ArrayTransport;
        $server = new ChildServerWithOverride($transport);

        $context = $server->createContext();

        $this->assertSame('Child Server', $context->implementation->name);
    }
}

