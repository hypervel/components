<?php

declare(strict_types=1);

namespace Hypervel\Tests\Cache;

use Hypervel\Cache\RedisLock;
use Hypervel\Contracts\Cache\RefreshableLock;
use Hypervel\Redis\PhpRedisConnection;
use Hypervel\Redis\RedisProxy;
use Hypervel\Tests\TestCase;
use InvalidArgumentException;
use JMac\Testing\Double;
use JMac\Testing\Integrations\PHPUnit\VerifiesDoubles;
use JMac\Testing\Matching\Argument;
use Redis;
use RedisCluster;
use RuntimeException;

class CacheRedisLockTest extends TestCase
{
    use VerifiesDoubles;

    public function testLockImplementsRefreshableLock(): void
    {
        [$lock] = $this->getLock();

        $this->assertInstanceOf(RefreshableLock::class, $lock);
    }

    public function testLockCanBeAcquired(): void
    {
        [$lock, $redis] = $this->getLock();

        $redis->expects('set')
            ->with('foo', Argument::type('string'), 'EX', 10, 'NX')
            ->returns(true);

        $this->assertTrue($lock->acquire());
    }

    public function testAcquireWithExpirationReturnsFalseWhenLockExists(): void
    {
        [$lock, $redis] = $this->getLock(seconds: 60);
        $redis->expects('set')
            ->with('foo', Argument::type('string'), 'EX', 60, 'NX')
            ->returns(false);

        $this->assertFalse($lock->acquire());
    }

    public function testLockCanBeAcquiredWithoutExpiration(): void
    {
        [$lock, $redis] = $this->getLock(seconds: 0);

        $redis->expects('setnx')
            ->with('foo', Argument::type('string'))
            ->returns(1);

        $this->assertTrue($lock->acquire());
    }

    public function testAcquireWithoutExpirationReturnsFalseWhenLockExists(): void
    {
        [$lock, $redis] = $this->getLock(seconds: 0);
        $redis->expects('setnx')
            ->with('foo', Argument::type('string'))
            ->returns(0);

        $this->assertFalse($lock->acquire());
    }

    public function testLockCanBeReleased(): void
    {
        [$lock, $redis] = $this->getLock();

        $connection = Double::for(CacheLockRedisConnection::class)->strict();
        $connection->expects('pack')
            ->with([$lock->owner()])
            ->returns(['packed-owner']);
        $connection->expects('eval')
            ->with(Argument::type('string'), 1, 'foo', 'packed-owner')
            ->returns(1);

        $redis->expects('withConnection')
            ->resolves(fn (callable $callback) => $callback($connection));

        $this->assertTrue($lock->release());
    }

    public function testReleaseReturnsFalseWhenNotOwner(): void
    {
        [$lock, $redis] = $this->getLock(seconds: 60);
        $connection = Double::for(CacheLockRedisConnection::class)->strict();
        $connection->expects('pack')
            ->with([$lock->owner()])
            ->returns(['packed-owner']);
        $connection->expects('eval')
            ->with(Argument::type('string'), 1, 'foo', 'packed-owner')
            ->returns(0);

        $redis->expects('withConnection')
            ->resolves(fn (callable $callback) => $callback($connection));

        $this->assertFalse($lock->release());
    }

    public function testLockCanBeForceReleased(): void
    {
        [$lock, $redis] = $this->getLock();

        $redis->expects('del')
            ->with('foo');

        $lock->forceRelease();
    }

    public function testOwnerReturnsTheOwnerIdentifier(): void
    {
        $redis = Double::for(CacheLockRedisProxy::class)->strict();

        $lock = new RedisLock($redis, 'lock:foo', 60, 'my-owner-id');

        $this->assertSame('my-owner-id', $lock->owner());
    }

    public function testOwnerIsAutoGeneratedWhenNotProvided(): void
    {
        [$lock] = $this->getLock();

        $this->assertNotEmpty($lock->owner());
    }

    public function testGetCallsAcquireAndExecutesCallbackOnSuccess(): void
    {
        [$lock, $redis] = $this->getLock(seconds: 60);
        $connection = Double::for(CacheLockRedisConnection::class)->strict();
        $connection->expects('pack')
            ->with([$lock->owner()])
            ->returns(['packed-owner']);
        $connection->expects('eval')
            ->returns(1);

        $redis->expects('set')
            ->with('foo', Argument::type('string'), 'EX', 60, 'NX')
            ->returns(true);
        $redis->expects('withConnection')
            ->resolves(fn (callable $callback) => $callback($connection));

        $result = $lock->get(fn () => 'callback-result');

        $this->assertSame('callback-result', $result);
    }

    public function testGetReturnsFalseWhenLockNotAcquired(): void
    {
        [$lock, $redis] = $this->getLock(seconds: 60);
        $redis->expects('set')
            ->with('foo', Argument::type('string'), 'EX', 60, 'NX')
            ->returns(false);

        $redis->expects('withConnection')->never();

        $result = $lock->get(fn () => $this->fail('A failed acquisition must not run the callback.'));

        $this->assertFalse($result);
    }

    public function testGetReleasesLockAfterCallbackEvenOnException(): void
    {
        [$lock, $redis] = $this->getLock(seconds: 60);
        $connection = Double::for(CacheLockRedisConnection::class)->strict();
        $connection->expects('pack')
            ->with([$lock->owner()])
            ->returns(['packed-owner']);
        $connection->expects('eval')
            ->returns(1);

        $redis->expects('set')
            ->returns(true);
        $redis->expects('withConnection')
            ->resolves(fn (callable $callback) => $callback($connection));

        $failure = new RuntimeException('test exception');

        try {
            $lock->get(static fn () => throw $failure);
            $this->fail('The callback failure was not thrown.');
        } catch (RuntimeException $exception) {
            $this->assertSame($failure, $exception);
        }
    }

    public function testRefreshExtendsLockTtl(): void
    {
        [$lock, $redis] = $this->getLock();

        $connection = Double::for(CacheLockRedisConnection::class)->strict();
        $connection->expects('pack')
            ->with([$lock->owner()])
            ->returns(['packed-owner']);
        $connection->expects('eval')
            ->with(Argument::type('string'), 1, 'foo', 'packed-owner', 10)
            ->returns(1);

        $redis->expects('withConnection')
            ->resolves(fn (callable $callback) => $callback($connection));

        $this->assertTrue($lock->refresh());
    }

    public function testRefreshWithCustomTtl(): void
    {
        [$lock, $redis] = $this->getLock();

        $connection = Double::for(CacheLockRedisConnection::class)->strict();
        $connection->expects('pack')
            ->with([$lock->owner()])
            ->returns(['packed-owner']);
        $connection->expects('eval')
            ->with(Argument::type('string'), 1, 'foo', 'packed-owner', 30)
            ->returns(1);

        $redis->expects('withConnection')
            ->resolves(fn (callable $callback) => $callback($connection));

        $this->assertTrue($lock->refresh(30));
    }

    public function testRefreshReturnsFalseWhenNotOwned(): void
    {
        [$lock, $redis] = $this->getLock();

        $connection = Double::for(CacheLockRedisConnection::class)->strict();
        $connection->expects('pack')
            ->with([$lock->owner()])
            ->returns(['packed-owner']);
        $connection->expects('eval')
            ->with(Argument::type('string'), 1, 'foo', 'packed-owner', 10)
            ->returns(0);

        $redis->expects('withConnection')
            ->resolves(fn (callable $callback) => $callback($connection));

        $this->assertFalse($lock->refresh());
    }

    public function testRefreshOnPermanentLockReturnsTrueWhenStillOwned(): void
    {
        [$lock, $redis] = $this->getLock(seconds: 0);

        $redis->expects('get')
            ->with('foo')
            ->returns($lock->owner());

        $this->assertTrue($lock->refresh());
    }

    public function testRefreshOnPermanentLockReturnsFalseWhenNotOwned(): void
    {
        [$lock, $redis] = $this->getLock(seconds: 0);

        $redis->expects('get')
            ->with('foo')
            ->returns('other-owner');

        $this->assertFalse($lock->refresh());
    }

    public function testIsLockedReturnsTrueWhenLockExists(): void
    {
        [$lock, $redis] = $this->getLock();

        $redis->expects('get')
            ->with('foo')
            ->returns('owner');

        $this->assertTrue($lock->isLocked());
    }

    public function testIsLockedReturnsFalseWhenLockDoesNotExist(): void
    {
        [$lock, $redis] = $this->getLock();

        $redis->expects('get')
            ->with('foo')
            ->returns(null);

        $this->assertFalse($lock->isLocked());
    }

    public function testRefreshWithExplicitZeroThrowsException(): void
    {
        [$lock] = $this->getLock(seconds: 10);

        $this->expectException(InvalidArgumentException::class);
        $this->expectExceptionMessageIs('Refresh requires a positive TTL.');

        $lock->refresh(0);
    }

    public function testRefreshWithNegativeSecondsThrowsException(): void
    {
        [$lock] = $this->getLock(seconds: 10);

        $this->expectException(InvalidArgumentException::class);
        $this->expectExceptionMessageIs('Refresh requires a positive TTL.');

        $lock->refresh(-5);
    }

    public function testGetRemainingLifetimeReturnsSeconds(): void
    {
        [$lock, $redis] = $this->getLock();

        $redis->expects('ttl')
            ->with('foo')
            ->returns(5);

        $this->assertSame(5.0, $lock->getRemainingLifetime());
    }

    public function testGetRemainingLifetimeReturnsNullWhenKeyDoesNotExist(): void
    {
        [$lock, $redis] = $this->getLock();

        $redis->expects('ttl')
            ->with('foo')
            ->returns(-2);

        $this->assertNull($lock->getRemainingLifetime());
    }

    public function testGetRemainingLifetimeReturnsNullWhenNoExpiry(): void
    {
        [$lock, $redis] = $this->getLock();

        $redis->expects('ttl')
            ->with('foo')
            ->returns(-1);

        $this->assertNull($lock->getRemainingLifetime());
    }

    public function testGetRemainingLifetimeReturnsZeroWhenExpired(): void
    {
        [$lock, $redis] = $this->getLock();

        $redis->expects('ttl')
            ->with('foo')
            ->returns(0);

        $this->assertSame(0.0, $lock->getRemainingLifetime());
    }

    public function testGetConnectionNameReturnsConnectionName(): void
    {
        [$lock, $redis] = $this->getLock(seconds: 60);
        $redis->expects('getName')->returns('default');

        $this->assertSame('default', $lock->getConnectionName());
    }

    /**
     * Get a RedisLock instance with mocked dependencies.
     */
    protected function getLock(int $seconds = 10): array
    {
        $redis = Double::for(CacheLockRedisProxy::class)->strict();
        $redis->allows('isQueueing')->returns(false);

        $lock = new RedisLock($redis, 'foo', $seconds);

        return [$lock, $redis];
    }
}

// Declare the dynamic commands so Double can verify their arguments and calls.
abstract class CacheLockRedisProxy extends RedisProxy
{
    /**
     * Store a value with optional expiration and existence conditions.
     */
    abstract public function set(string $key, mixed $value, mixed $expireResolution = null, ?int $expireTTL = null, ?string $flag = null): mixed;

    /**
     * Store a value only when the key does not exist.
     */
    abstract public function setnx(string $key, mixed $value): int;

    /**
     * Retrieve a value.
     */
    abstract public function get(string $key): mixed;

    /**
     * Delete the given keys.
     */
    abstract public function del(array|string $key, string ...$otherKeys): Redis|RedisCluster|int|false;

    /**
     * Get the remaining key lifetime.
     */
    abstract public function ttl(string $key): Redis|RedisCluster|int|false;
}

abstract class CacheLockRedisConnection extends PhpRedisConnection
{
    /**
     * Execute a Lua script with separate keys and arguments.
     */
    abstract public function eval(string $script, int $numberOfKeys, mixed ...$arguments): mixed;
}
