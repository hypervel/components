CREATE EXTENSION IF NOT EXISTS hstore;
CREATE EXTENSION IF NOT EXISTS ltree;
CREATE EXTENSION IF NOT EXISTS citext;

CREATE TYPE public.mood AS ENUM ('sad', 'ok', 'happy');
CREATE TYPE public.complex AS (r double precision, i double precision);
CREATE DOMAIN public.positive_int AS integer CHECK (VALUE > 0);
CREATE TYPE public.float8_range AS RANGE (subtype = float8);

CREATE TABLE public.all_types (
    -- serial / identity
    id                    bigserial PRIMARY KEY,
    small_id              smallserial,
    plain_serial          serial,
    identity_col          integer GENERATED BY DEFAULT AS IDENTITY,
    identity_always       bigint GENERATED ALWAYS AS IDENTITY,

    -- numeric
    c_smallint            smallint,
    c_int2                int2,
    c_integer             integer,
    c_int                 int,
    c_int4                int4,
    c_bigint              bigint NOT NULL,
    c_int8                int8,
    c_decimal             decimal,
    c_decimal_p           decimal(10, 2),
    c_numeric             numeric,
    c_numeric_p           numeric(14, 4),
    c_real                real,
    c_float4              float4,
    c_double              double precision,
    c_float8              float8,
    c_float               float,
    c_float_p             float(24),
    c_money               money,

    -- character
    c_varchar             character varying(255),
    c_varchar_short       varchar(64),
    c_varchar_nolen       character varying,
    c_char                character(10),
    c_char_short          char(2),
    c_bpchar              bpchar,
    c_text                text NOT NULL,
    c_citext              citext,
    c_name                name,

    -- binary
    c_bytea               bytea,

    -- date/time
    c_timestamp           timestamp,
    c_timestamp_p         timestamp(3),
    c_timestamp_wo        timestamp without time zone,
    c_timestamp_wo_p      timestamp(0) without time zone,
    c_timestamptz         timestamptz,
    c_timestamp_tz        timestamp with time zone,
    c_timestamp_tz_p      timestamp(6) with time zone,
    c_date                date,
    c_time                time,
    c_time_p              time(2),
    c_time_wo             time without time zone,
    c_timetz              timetz,
    c_time_tz             time with time zone,
    c_interval            interval,
    c_interval_f          interval day to second(3),
    c_interval_y          interval year to month,

    -- boolean
    c_boolean             boolean NOT NULL DEFAULT false,
    c_bool                bool,

    -- enum / composite / domain
    c_mood                public.mood,
    c_complex             public.complex,
    c_positive            public.positive_int,

    -- geometric
    c_point               point,
    c_line                line,
    c_lseg                lseg,
    c_box                 box,
    c_path                path,
    c_polygon             polygon,
    c_circle              circle,

    -- network
    c_cidr                cidr,
    c_inet                inet,
    c_macaddr             macaddr,
    c_macaddr8            macaddr8,

    -- bit strings
    c_bit                 bit(3),
    c_bit1                bit,
    c_varbit              bit varying(5),
    c_varbit_nolen        varbit,

    -- text search
    c_tsvector            tsvector,
    c_tsquery             tsquery,

    -- uuid / xml / json
    c_uuid                uuid,
    c_xml                 xml,
    c_json                json,
    c_jsonb               jsonb,
    c_jsonpath            jsonpath,

    -- arrays
    c_int_array           integer[],
    c_int_array_sized     integer[3],
    c_text_array          text[],
    c_varchar_array       character varying(255)[],
    c_int_matrix          integer[][],
    c_array_kw            int ARRAY[4],
    c_mood_array          public.mood[],

    -- ranges & multiranges
    c_int4range           int4range,
    c_int8range           int8range,
    c_numrange            numrange,
    c_tsrange             tsrange,
    c_tstzrange           tstzrange,
    c_daterange           daterange,
    c_int4multirange      int4multirange,
    c_datemultirange      datemultirange,
    c_custom_range        public.float8_range,

    -- extensions
    c_hstore              hstore,
    c_ltree               ltree,

    -- system / oid types
    c_oid                 oid,
    c_regclass            regclass,
    c_pg_lsn              pg_lsn,
    c_pg_snapshot         pg_snapshot,

    -- generated / computed
    c_generated           integer GENERATED ALWAYS AS (c_integer * 2) STORED,

    -- Hypervel timestamp conventions
    created_at            timestamp(0) without time zone,
    updated_at            timestamp(0) without time zone,
    deleted_at            timestamp(0) without time zone,

    CONSTRAINT all_types_check CHECK (c_integer > 0)
);

COMMENT ON TABLE public.all_types IS 'Every PostgreSQL data type';
COMMENT ON COLUMN public.all_types.c_text IS 'a text column';

CREATE INDEX all_types_c_text_idx ON public.all_types USING btree (c_text);
CREATE INDEX all_types_jsonb_idx ON public.all_types USING gin (c_jsonb);
CREATE UNIQUE INDEX all_types_uuid_idx ON public.all_types USING btree (c_uuid) WHERE (c_uuid IS NOT NULL);

CREATE TABLE public.related (
    id         bigserial PRIMARY KEY,
    all_type_id bigint NOT NULL REFERENCES public.all_types(id) ON DELETE CASCADE,
    label      character varying(100) NOT NULL
);

CREATE SCHEMA IF NOT EXISTS reporting;
CREATE TABLE reporting.summaries (
    id    bigserial PRIMARY KEY,
    total numeric(12, 2) NOT NULL DEFAULT 0
);

CREATE VIEW public.active_types AS SELECT id, c_text FROM public.all_types WHERE deleted_at IS NULL;

CREATE TABLE public.partitioned (
    id         bigserial NOT NULL,
    created_at timestamp(0) without time zone NOT NULL
) PARTITION BY RANGE (created_at);

CREATE FUNCTION public.touch_updated_at() RETURNS trigger AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER all_types_touch BEFORE UPDATE ON public.all_types
    FOR EACH ROW EXECUTE FUNCTION public.touch_updated_at();
