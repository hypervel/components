<?php

declare(strict_types=1);

namespace Hypervel\Tests\Integration\SchemaParser\Database\Postgres;

use Hypervel\Filesystem\Filesystem;
use Hypervel\SchemaParser\Deferral;
use Hypervel\SchemaParser\GenerationType;
use Hypervel\SchemaParser\Identity;
use Hypervel\SchemaParser\PostgresParser;
use Hypervel\SchemaParser\ReferentialAction;
use Hypervel\Support\Facades\DB;
use Hypervel\Testing\ParallelTesting;
use Hypervel\Tests\Integration\Database\Postgres\PostgresTestCase;
use Symfony\Component\Process\Process;

class SchemaParserTest extends PostgresTestCase
{
    public function testNativeDumpMatchesTheDatabaseSchema(): void
    {
        $connection = DB::connection();
        $version = $connection->getServerVersion();
        $files = $this->app->make(Filesystem::class);
        $directory = ParallelTesting::tempDir('SchemaParserPostgres');
        $files->deleteDirectory($directory);
        $files->ensureDirectoryExists($directory);
        $this->beforeApplicationDestroyed(static fn () => $files->deleteDirectory($directory));
        $migration = "schema_parser_'copy_marker";

        $connection->statement('CREATE SCHEMA schema_parser');
        try {
            $connection->statement("CREATE TYPE schema_parser.mood AS ENUM ('ok', 'it''s broken')");
            $connection->statement('CREATE DOMAIN schema_parser.positive AS integer DEFAULT 5 NOT NULL CHECK (VALUE > 0)');
            $connection->statement(<<<'SQL'
                CREATE TABLE schema_parser.parents (
                    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
                    name text DEFAULT 'parent' NOT NULL,
                    CONSTRAINT parent_name CHECK (name <> '')
                )
                SQL);
            $connection->statement('CREATE TABLE schema_parser.inherited (extra text) INHERITS (schema_parser.parents)');
            $connection->statement(<<<'SQL'
                CREATE TABLE schema_parser.records (
                    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    serial_id bigserial,
                    parent_id bigint,
                    state schema_parser.mood DEFAULT 'ok',
                    score schema_parser.positive DEFAULT NULL,
                    total numeric(12, 2) DEFAULT 1.25,
                    numbers integer[] DEFAULT ARRAY[1, NULL, 3],
                    label text COLLATE "C"
                )
                SQL);
            $connection->statement(<<<'SQL'
                ALTER TABLE schema_parser.records ADD CONSTRAINT record_parent
                FOREIGN KEY (parent_id) REFERENCES schema_parser.parents (id)
                ON UPDATE CASCADE ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED NOT VALID
                SQL);
            $connection->statement('ALTER TABLE schema_parser.records ADD CONSTRAINT positive_total CHECK (total >= 0) NOT VALID');
            $connection->statement("COMMENT ON COLUMN schema_parser.records.label IS 'user''s label'");
            $connection->statement('CREATE INDEX mixed_key ON schema_parser.records (parent_id, lower(label))');
            if (version_compare($version, '11.0', '>=')) {
                $connection->statement('CREATE UNIQUE INDEX state_label ON schema_parser.records (state, label) INCLUDE (total)'
                    . (version_compare($version, '15.0', '>=') ? ' NULLS NOT DISTINCT' : ''));
            }
            if (version_compare($version, '12.0', '>=')) {
                $connection->statement('ALTER TABLE schema_parser.records ADD COLUMN doubled numeric GENERATED ALWAYS AS (total * 2) STORED');
            }
            if (version_compare($version, '18.0', '>=')) {
                $connection->statement('ALTER TABLE schema_parser.records ADD COLUMN virtual_total numeric GENERATED ALWAYS AS (total + 2)');
                $connection->statement('ALTER TABLE schema_parser.records ADD CONSTRAINT score_nn NOT NULL score NOT VALID');
            }
            $connection->statement('CREATE VIEW schema_parser.report AS SELECT id, label FROM schema_parser.records WITH LOCAL CHECK OPTION');
            $connection->table('migrations')->insert(['migration' => $migration, 'batch' => 0]);

            $path = $directory . '/schema.sql';
            $connection->getSchemaState(processFactory: static fn (string $command): Process => Process::fromShellCommandline($command)->setTimeout(30))
                ->dump($connection, $path);
            $sql = $files->get($path);
            $schema = (new PostgresParser)->parse($sql);
            $table = $schema->table('records', 'schema_parser');
            $columns = array_column($connection->getSchemaBuilder()->getColumns('schema_parser.records'), null, 'name');
            $nullability = array_column($connection->select(<<<'SQL'
                SELECT a.attname AS name, NOT (a.attnotnull AND coalesce(c.convalidated, true)) AS nullable
                FROM pg_attribute a
                LEFT JOIN pg_constraint c ON c.conrelid = a.attrelid AND c.contype = 'n' AND a.attnum = ANY(c.conkey)
                WHERE a.attrelid = 'schema_parser.records'::regclass AND a.attnum > 0 AND NOT a.attisdropped
                SQL), 'nullable', 'name');

            $this->assertSame([], $schema->issues);
            $this->assertCount(version_compare($version, '18.0', '>=') ? 1 : 0, $table->issues);
            $this->assertSame(array_keys($columns), array_column($table->columns, 'name'));
            foreach ($table->columns as $column) {
                $this->assertSame((bool) $nullability[$column->name], $column->nullable, $column->name);
                $this->assertSame($columns[$column->name]['auto_increment'], $column->autoIncrement, $column->name);
                $this->assertSame($columns[$column->name]['comment'], $column->comment, $column->name);
            }
            $this->assertSame(Identity::Always, $schema->table('parents')->column('id')->identity);
            $this->assertSame(Identity::ByDefault, $table->column('id')->identity);
            $this->assertTrue($table->column('serial_id')->autoIncrement);
            $this->assertSame(['ok', "it's broken"], $schema->enum('mood')->values);
            $this->assertFalse($schema->domain('positive')->nullable);
            $this->assertTrue($table->column('score')->nullable);
            $this->assertSame('NULL::integer', $table->column('score')->default);
            $this->assertSame('positive', $table->column('score')->type->name);
            $this->assertSame('int4', $table->column('score')->type->base->name);
            $this->assertSame(['12', '2'], $table->column('total')->type->modifiers);
            $this->assertSame(1, $table->column('numbers')->type->dimensions);
            $this->assertSame('pg_catalog."C"', $table->column('label')->collation);

            $indexes = array_column($table->indexes, null, 'name');
            $this->assertSame('parent_id', $indexes['mixed_key']->columns[0]->name);
            $this->assertNull($indexes['mixed_key']->columns[1]->name);
            $this->assertStringContainsString('lower(label)', $indexes['mixed_key']->columns[1]->expression);
            if (version_compare($version, '11.0', '>=')) {
                $this->assertSame(['state', 'label'], array_column($indexes['state_label']->columns, 'name'));
                $this->assertSame(['total'], $indexes['state_label']->include);
                $this->assertSame(version_compare($version, '15.0', '>='), $indexes['state_label']->nullsNotDistinct);
            }
            if (version_compare($version, '12.0', '>=')) {
                $this->assertSame(GenerationType::Stored, $table->column('doubled')->generation->type);
            }
            if (version_compare($version, '18.0', '>=')) {
                $this->assertSame(GenerationType::Virtual, $table->column('virtual_total')->generation->type);
                $this->assertStringContainsString('has not been validated', $table->issues[0]->message);
            }
            $this->assertSame(ReferentialAction::Cascade, $table->foreignKeys[0]->onUpdate);
            $this->assertSame(ReferentialAction::SetNull, $table->foreignKeys[0]->onDelete);
            $this->assertSame(Deferral::Deferred, $table->foreignKeys[0]->deferral);
            $this->assertFalse($table->foreignKeys[0]->valid);
            $this->assertFalse($table->checks[0]->valid);
            $child = $schema->table('inherited');
            $this->assertSame(['id', 'name', 'extra'], array_column($child->columns, 'name'));
            $this->assertNull($child->column('id')->identity);
            $this->assertFalse($child->column('id')->autoIncrement);
            $this->assertNull($child->primaryKey());
            $this->assertSame('parent_name', $child->checks[0]->name);
            $this->assertNotNull($schema->view('report'));
            $this->assertStringNotContainsString('CHECK OPTION', $schema->view('report')->definition);
            $this->assertStringContainsString('COPY public.migrations ', $sql);
            $this->assertStringContainsString($migration, $sql);
        } finally {
            $connection->statement('DROP SCHEMA schema_parser CASCADE');
            $connection->table('migrations')->where('migration', $migration)->delete();
        }
    }
}
